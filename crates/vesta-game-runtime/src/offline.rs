//! Temporary Java Edition responder. The process owner must close this before
//! launching Minecraft. Connections are bounded and never transferred to a child.
use serde::{Deserialize, Serialize};
use std::{
    collections::HashMap,
    io::{Read, Write},
    net::{IpAddr, SocketAddr, TcpListener, TcpStream},
    sync::{
        Arc, Mutex, RwLock,
        atomic::{AtomicBool, Ordering},
        mpsc,
    },
    thread::{self, JoinHandle},
    time::{Duration, Instant},
};

const WAIT: Duration = Duration::from_millis(750);
const MAX_FRAME: usize = 4096;
const MAX_STATUS: usize = 12_000;
const MAX_CONNECTIONS: usize = 8;
const SOURCE_COOLDOWN: Duration = Duration::from_secs(10);

#[derive(Clone, Debug, Eq, PartialEq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Configuration {
    pub address: SocketAddr,
    /// Public status generated by the trusted renderer, never raw remote input.
    pub status_json: String,
    pub disconnect: String,
    pub wake: bool,
}
impl Configuration {
    pub fn validate(&self) -> Result<(), &'static str> {
        if self.address.port() == 0
            || self.status_json.len() > MAX_STATUS
            || self.disconnect.len() > 4096
            || self.disconnect.chars().any(|c| c.is_control())
        {
            return Err("offline_configuration_invalid");
        }
        let status: serde_json::Value =
            serde_json::from_str(&self.status_json).map_err(|_| "offline_configuration_invalid")?;
        // Offline responses cannot invent player identities or live players.
        if status.pointer("/players/online").and_then(|v| v.as_u64()) != Some(0)
            || status
                .pointer("/players/max")
                .and_then(|v| v.as_u64())
                .is_none()
            || status.pointer("/players/sample").is_some()
            || status.get("description").is_none()
            || status
                .pointer("/version/protocol")
                .and_then(|v| v.as_i64())
                .is_none()
        {
            return Err("offline_configuration_invalid");
        }
        Ok(())
    }
}

pub struct Responder {
    configuration: Configuration,
    current: Arc<RwLock<Configuration>>,
    stop: Arc<AtomicBool>,
    worker: Option<JoinHandle<()>>,
    wake: mpsc::Receiver<IpAddr>,
}
impl Responder {
    pub fn bind(configuration: Configuration) -> Result<Self, &'static str> {
        configuration.validate()?;
        let listener =
            TcpListener::bind(configuration.address).map_err(|_| "offline_bind_failed")?;
        listener
            .set_nonblocking(true)
            .map_err(|_| "offline_bind_failed")?;
        let stop = Arc::new(AtomicBool::new(false));
        let flag = stop.clone();
        let current = Arc::new(RwLock::new(configuration.clone()));
        let config = current.clone();
        let (sender, wake) = mpsc::sync_channel(16);
        let worker = thread::Builder::new()
            .name("vesta-offline-status".into())
            .spawn(move || {
                let mut clients: Vec<JoinHandle<()>> = Vec::new();
                let sources: Arc<Mutex<HashMap<IpAddr, Instant>>> = Arc::default();
                while !flag.load(Ordering::Acquire) {
                    let mut index = 0;
                    while index < clients.len() {
                        if clients[index].is_finished() {
                            let _ = clients.swap_remove(index).join();
                        } else {
                            index += 1;
                        }
                    }
                    match listener.accept() {
                        Ok((stream, address)) => {
                            if clients.len() >= MAX_CONNECTIONS {
                                drop(stream);
                                continue;
                            }
                            let config = match config.read() {
                                Ok(config) => config.clone(),
                                Err(_) => {
                                    drop(stream);
                                    continue;
                                }
                            };
                            let sender = sender.clone();
                            let sources = sources.clone();
                            if let Ok(worker) = thread::Builder::new()
                                .name("vesta-offline-client".into())
                                .spawn(move || {
                                    let _ = serve(stream, &config, address.ip(), sender, sources);
                                })
                            {
                                clients.push(worker);
                            }
                        }
                        Err(error) if error.kind() == std::io::ErrorKind::WouldBlock => {
                            thread::sleep(Duration::from_millis(10))
                        }
                        Err(_) => break,
                    }
                }
                // Release the listening socket before joining bounded clients.
                drop(listener);
                for client in clients {
                    let _ = client.join();
                }
            })
            .map_err(|_| "offline_worker_failed")?;
        Ok(Self {
            configuration,
            current,
            stop,
            worker: Some(worker),
            wake,
        })
    }
    pub fn configuration(&self) -> &Configuration {
        &self.configuration
    }
    /// Refresh public presentation/wake policy on the same bound socket. Source
    /// budgets, accepted clients and pending wake hints retain their ownership.
    pub fn update(&mut self, configuration: Configuration) -> Result<(), &'static str> {
        configuration.validate()?;
        if configuration.address != self.configuration.address {
            return Err("offline_address_changed");
        }
        if self.stop.load(Ordering::Acquire)
            || self
                .worker
                .as_ref()
                .is_none_or(|worker| worker.is_finished())
        {
            return Err("offline_worker_failed");
        }
        *self
            .current
            .write()
            .map_err(|_| "offline_configuration_failed")? = configuration.clone();
        self.configuration = configuration;
        Ok(())
    }
    pub fn take_wakes(&self) -> Vec<IpAddr> {
        self.wake.try_iter().take(16).collect()
    }
    /// Returns only after listener and every accepted stream are closed. Failure
    /// is uncertain port ownership and must prevent launch.
    pub fn close(&mut self) -> Result<(), &'static str> {
        self.stop.store(true, Ordering::Release);
        if let Some(worker) = self.worker.take() {
            worker.join().map_err(|_| "offline_release_uncertain")?;
        }
        Ok(())
    }
}
impl Drop for Responder {
    fn drop(&mut self) {
        let _ = self.close();
    }
}

fn serve(
    mut stream: TcpStream,
    config: &Configuration,
    source: IpAddr,
    sender: mpsc::SyncSender<IpAddr>,
    sources: Arc<Mutex<HashMap<IpAddr, Instant>>>,
) -> std::io::Result<()> {
    // Windows may inherit listener mode on accepted sockets.
    stream.set_nonblocking(false)?;
    stream.set_read_timeout(Some(WAIT))?;
    stream.set_write_timeout(Some(WAIT))?;
    let deadline = Instant::now() + WAIT;
    let handshake = frame(&mut stream, deadline)?;
    let mut input = handshake.as_slice();
    if take_varint(&mut input)? != 0 {
        return Err(invalid());
    }
    let protocol = take_varint(&mut input)?;
    if protocol < 0 {
        return Err(invalid());
    }
    let host_len = usize::try_from(take_varint(&mut input)?).map_err(|_| invalid())?;
    if host_len == 0 || host_len > 255 || input.len() < host_len + 2 {
        return Err(invalid());
    }
    std::str::from_utf8(&input[..host_len]).map_err(|_| invalid())?;
    input = &input[host_len + 2..];
    let next = take_varint(&mut input)?;
    if !input.is_empty() {
        return Err(invalid());
    }
    match next {
        1 => {
            if frame(&mut stream, deadline)?.as_slice() != [0] {
                return Err(invalid());
            }
            let mut status: serde_json::Value =
                serde_json::from_str(&config.status_json).map_err(|_| invalid())?;
            // -1 denotes protocol-neutral temporary Vesta status, not actual
            // Minecraft version compatibility. Echo lets clients attempt wake;
            // the real server negotiates compatibility on the later reconnect.
            if status.pointer("/version/protocol").and_then(|v| v.as_i64()) == Some(-1) {
                status["version"]["protocol"] = protocol.into();
            }
            write_text(&mut stream, &status.to_string(), deadline)?;
            let ping = frame(&mut stream, deadline)?;
            if ping.len() != 9 || ping[0] != 1 {
                return Err(invalid());
            }
            write_frame(&mut stream, &ping, deadline)
        }
        2 => {
            // Only a complete, bounded Java login-start frame requests wake.
            let login = frame(&mut stream, deadline)?;
            let mut payload = login.as_slice();
            if take_varint(&mut payload)? != 0 {
                return Err(invalid());
            }
            let length = usize::try_from(take_varint(&mut payload)?).map_err(|_| invalid())?;
            if !(1..=16).contains(&length) || payload.len() < length {
                return Err(invalid());
            }
            let username = &payload[..length];
            if !username
                .iter()
                .all(|b| b.is_ascii_alphanumeric() || *b == b'_')
            {
                return Err(invalid());
            }
            // Modern vanilla adds a UUID, legacy versions end after the name.
            if ![0, 16].contains(&(payload.len() - length)) {
                return Err(invalid());
            }
            if config.wake
                && let Ok(mut sources) = sources.lock()
            {
                let now = Instant::now();
                sources.retain(|_, at| now.duration_since(*at) < SOURCE_COOLDOWN);
                if !sources.contains_key(&source) && sources.len() < 256 {
                    sources.insert(source, now);
                    let _ = sender.try_send(source);
                }
            }
            let component = serde_json::from_str::<serde_json::Value>(&config.disconnect)
                .ok()
                .filter(|value| value.is_object() || value.is_array())
                .unwrap_or_else(|| serde_json::json!({"text":config.disconnect}));
            write_text(&mut stream, &component.to_string(), deadline)
        }
        _ => Err(invalid()),
    }
}
fn invalid() -> std::io::Error {
    std::io::Error::new(std::io::ErrorKind::InvalidData, "offline_protocol_invalid")
}
fn read_byte(stream: &mut TcpStream, deadline: Instant) -> std::io::Result<u8> {
    let remaining = deadline
        .checked_duration_since(Instant::now())
        .filter(|d| !d.is_zero())
        .ok_or_else(invalid)?;
    stream.set_read_timeout(Some(remaining))?;
    let mut byte = [0];
    stream.read_exact(&mut byte)?;
    Ok(byte[0])
}
fn frame(stream: &mut TcpStream, deadline: Instant) -> std::io::Result<Vec<u8>> {
    let mut length = 0u32;
    for index in 0..5 {
        let byte = read_byte(stream, deadline)?;
        if index == 4 && byte > 7 {
            return Err(invalid());
        }
        length |= u32::from(byte & 127) << (index * 7);
        if byte & 128 == 0 {
            if length == 0 || length as usize > MAX_FRAME {
                return Err(invalid());
            }
            let mut bytes = Vec::with_capacity(length as usize);
            for _ in 0..length {
                bytes.push(read_byte(stream, deadline)?);
            }
            return Ok(bytes);
        }
    }
    Err(invalid())
}
fn take_varint(input: &mut &[u8]) -> std::io::Result<i32> {
    let mut value = 0u32;
    for index in 0..5 {
        let byte = *input.first().ok_or_else(invalid)?;
        *input = &input[1..];
        if index == 4 && byte > 15 {
            return Err(invalid());
        }
        value |= u32::from(byte & 127) << (index * 7);
        if byte & 128 == 0 {
            return Ok(value as i32);
        }
    }
    Err(invalid())
}
fn put_varint(mut value: usize, out: &mut Vec<u8>) {
    loop {
        let byte = (value & 127) as u8;
        value >>= 7;
        out.push(byte | if value == 0 { 0 } else { 128 });
        if value == 0 {
            break;
        }
    }
}
fn write_text(stream: &mut TcpStream, text: &str, deadline: Instant) -> std::io::Result<()> {
    let mut packet = vec![0];
    put_varint(text.len(), &mut packet);
    packet.extend_from_slice(text.as_bytes());
    write_frame(stream, &packet, deadline)
}
fn write_frame(stream: &mut TcpStream, packet: &[u8], deadline: Instant) -> std::io::Result<()> {
    let mut prefix = Vec::new();
    put_varint(packet.len(), &mut prefix);
    prefix.extend_from_slice(packet);
    let mut remaining = prefix.as_slice();
    while !remaining.is_empty() {
        let wait = deadline
            .checked_duration_since(Instant::now())
            .filter(|d| !d.is_zero())
            .ok_or_else(invalid)?;
        stream.set_write_timeout(Some(wait))?;
        match stream.write(remaining) {
            Ok(0) => return Err(invalid()),
            Ok(count) => remaining = &remaining[count..],
            Err(error) if error.kind() == std::io::ErrorKind::Interrupted => {}
            Err(error) => return Err(error),
        }
    }
    Ok(())
}
