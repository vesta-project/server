package com.vesta.sync.auth;

import java.security.SecureRandom;
import java.time.Instant;
import java.util.Locale;
import java.util.Map;
import java.util.Optional;
import java.util.UUID;
import java.util.concurrent.ConcurrentHashMap;

/**
 * Short-lived link codes that bind a Minecraft UUID to a launcher session.
 */
public final class LinkCodeService {

    public static final class PendingLink {
        public final String code;
        public final UUID playerUuid;
        public final Instant expiresAt;

        public PendingLink(String code, UUID playerUuid, Instant expiresAt) {
            this.code = code;
            this.playerUuid = playerUuid;
            this.expiresAt = expiresAt;
        }

        public boolean isExpired() {
            return Instant.now().isAfter(expiresAt);
        }
    }

    private static final char[] ALPHABET = "ABCDEFGHJKLMNPQRSTUVWXYZ23456789".toCharArray();
    private static final SecureRandom RANDOM = new SecureRandom();

    private final ConcurrentHashMap<String, PendingLink> pending = new ConcurrentHashMap<>();
    private final long ttlSeconds;

    public LinkCodeService(long ttlSeconds) {
        this.ttlSeconds = ttlSeconds;
    }

    public String createCode(UUID playerUuid) {
        purge();
        String code = randomCode(6);
        pending.put(code, new PendingLink(code, playerUuid, Instant.now().plusSeconds(ttlSeconds)));
        return code;
    }

    /** Register a code generated by the mod (same TTL). */
    public void noteExternal(String code, UUID playerUuid) {
        if (code == null || playerUuid == null) {
            return;
        }
        purge();
        String key = code.trim().toUpperCase(Locale.ROOT);
        pending.put(key, new PendingLink(key, playerUuid, Instant.now().plusSeconds(ttlSeconds)));
    }

    public Optional<UUID> redeem(String code) {
        if (code == null || code.trim().isEmpty()) {
            return Optional.empty();
        }
        String key = code.trim().toUpperCase(Locale.ROOT);
        PendingLink link = pending.remove(key);
        if (link == null || link.isExpired()) {
            return Optional.empty();
        }
        return Optional.of(link.playerUuid);
    }

    public Optional<PendingLink> peek(String code) {
        if (code == null) {
            return Optional.empty();
        }
        PendingLink link = pending.get(code.trim().toUpperCase(Locale.ROOT));
        if (link == null || link.isExpired()) {
            return Optional.empty();
        }
        return Optional.of(link);
    }

    public void purge() {
        for (Map.Entry<String, PendingLink> e : pending.entrySet()) {
            if (e.getValue().isExpired()) {
                pending.remove(e.getKey(), e.getValue());
            }
        }
    }

    private static String randomCode(int len) {
        char[] out = new char[len];
        for (int i = 0; i < len; i++) {
            out[i] = ALPHABET[RANDOM.nextInt(ALPHABET.length)];
        }
        return new String(out);
    }
}
